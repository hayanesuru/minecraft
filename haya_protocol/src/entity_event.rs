impl mser::Write for EntityEvent {
    unsafe fn write(&self, w: &mut mser::Writer) {
        unsafe {
            w.write_byte(self.id());
        }
    }

    fn len_s(&self) -> usize {
        1
    }
}

impl<'a> mser::Read<'a> for EntityEvent {
    fn read(buf: &mut mser::Reader<'a>) -> Result<Self, mser::Error> {
        Ok(Self::new(buf.read_byte()?))
    }
}
